ulang_3029 = int(input("Masukkan jumlah perulangan: "))
print("perulangan ke-0 sampai ke-",ulang_3029-1)
for i_3029 in range(ulang_3029):
    print(i_3029,end=" ")
print()
print("perulangan ke-1 sampai ke-",ulang_3029)
for i_3029 in range(ulang_3029):
    print(i_3029+1,end=" ")